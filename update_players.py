"""
Builds players_data.js for the Premier League Predictor page from
player_match_stats.csv (the file made by the soccerdata loop).

Run it in the same folder as the CSV and index.html, either as a notebook
cell or with:  python update_players.py
Re-run it whenever you refresh the CSV to update the goalscorer odds.
"""
import html
import json

import pandas as pd

SEASON = 2627          # current season, as stored in the CSV
TOP_N = 8              # players kept per team (the page shows the top 6)
PRIOR_XG_PER_90 = 0.15 # early-season shrinkage: every player starts with
PRIOR_MINUTES = 90     # 90 "phantom" minutes at 0.15 xG/90

# Understat team names -> the names used on the page
TEAM_NAMES = {
    "Manchester City": "Man City",
    "Manchester United": "Man United",
    "Newcastle United": "Newcastle",
    "Nottingham Forest": "Nott'm Forest",
    "Wolverhampton Wanderers": "Wolves",
    "Tottenham Hotspur": "Tottenham",
    "Brighton & Hove Albion": "Brighton",
    "Hull City": "Hull",
    "Coventry City": "Coventry",
    "Leeds United": "Leeds",
    "Leicester City": "Leicester",
    "Ipswich Town": "Ipswich",
    "West Ham United": "West Ham",
    "AFC Bournemouth": "Bournemouth",
}

df = pd.read_csv("player_match_stats.csv")
df = df[df["season"].astype(str) == str(SEASON)].copy()
df["team"] = df["team"].replace(TEAM_NAMES)
df["player"] = df["player"].map(html.unescape)  # "O&#039;Shea" -> "O'Shea"

# Matches each team has played this season
games = df.groupby("team")["game"].nunique()

# Leave out players who have played for more than one club this season
clubs = df.groupby("player")["team"].nunique()
movers = clubs[clubs > 1].index
if len(movers):
    print("Left out (played for more than one club):", ", ".join(movers))
df = df[~df["player"].isin(movers)]

season = (
    df.groupby(["team", "player"])
    .agg(goals=("goals", "sum"), xg=("xg", "sum"),
         minutes=("minutes", "sum"), apps=("game", "nunique"))
    .reset_index()
)

# Expected xG per team match: shrunk xG-per-minute x average minutes per team match
rate = (season["xg"] + PRIOR_XG_PER_90 * PRIOR_MINUTES / 90) / (season["minutes"] + PRIOR_MINUTES)
season["contrib"] = rate * season["minutes"] / season["team"].map(games)

players = {}
for team, g in season.groupby("team"):
    g = g.sort_values("contrib", ascending=False)
    players[team] = {
        "games": int(games[team]),
        "sum": round(float(g["contrib"].sum()), 4),
        "p": [
            [r.player, round(float(r.contrib), 4), int(r.goals),
             round(float(r.xg), 2), int(r.minutes), int(r.apps)]
            for r in g.head(TOP_N).itertuples()
        ],
    }

with open("players_data.js", "w", encoding="utf-8") as f:
    f.write("// Generated by update_players.py. "
            "Per team: [player, expected per-match xG contribution, goals, xG, minutes, apps]\n")
    f.write("var PLAYERS = " + json.dumps(players, ensure_ascii=False) + ";\n")

page_teams = {
    "Man City", "Arsenal", "Liverpool", "Aston Villa", "Man United", "Newcastle", "Chelsea",
    "Tottenham", "Brighton", "Brentford", "West Ham", "Crystal Palace", "Fulham", "Everton",
    "Wolves", "Bournemouth", "Nott'm Forest", "Leicester", "Leeds", "Southampton", "Burnley",
    "Sunderland", "Watford", "Luton", "Norwich", "Ipswich", "Sheffield United", "Coventry", "Hull",
}
unknown = sorted(set(players) - page_teams)
if unknown:
    print("Team names the page won't recognise (add them to TEAM_NAMES):", unknown)

print(f"Wrote players_data.js: {len(players)} teams, "
      f"{min(games)}-{max(games)} matches played")
